const CDN = 'https://images.squarespace-cdn.com/content/v1/6142b7c78f031b447c0f467c/';
const img = (path, w) => CDN + path + '?format=' + (w || 1500) + 'w';
const esc = s => String(s).replace(/"/g, '&quot;');

/* One tile, used by every gallery on the site. */
function tileHTML(w, opts) {
  opts = opts || {};
  return '<div class="tile rv ' + (opts.cls || '') + '" role="button" tabindex="0"' +
         ' data-c="' + w.c + '"' +
         ' data-full="' + img(w.f, 2000) + '"' +
         ' data-cap="' + esc(w.loc || w.alt) + '">' +
         '<img src="' + img(w.f, opts.thumb || 900) + '" alt="' + esc(w.alt) + '" loading="lazy">' +
         (w.loc ? '<span class="tile-cap">' + w.loc + '</span>' : '') +
         '</div>';
}

